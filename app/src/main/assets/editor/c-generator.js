(function(root){
  'use strict';
  var OP={f:2,gv:3,l:4,la:5,lw:6,r:7,rf:8,rr:9,c:10,cw:11,tri:12,t:13};
  function ident(s){return s.replace(/[^A-Za-z0-9]+/g,'_').toUpperCase()}
  function keyOf(value){return JSON.stringify(value)}
  function lines(values,suffix,hex){
    var out=[],line=' ';
    values.forEach(function(v){
      var item=hex?'0x'+v.toString(16).padStart(2,'0'):(v>>>0)+suffix;
      if(line.length+item.length+1>116){out.push(line);line=' '}
      line+=item+',';
    });
    if(line.trim())out.push(line);return out.join('\n');
  }
  function cString(s){return String(s).replace(/\\/g,'\\\\').replace(/"/g,'\\"')}

  function generate(sceneEntries){
    var strings=[0],stringOffsets=new Map(),clips=[],clipIds=new Map();
    var primitives=[],primitiveIds=new Map(),blocks=[],blockIds=new Map();
    var sceneBlockIds=[],scenes=[];
    var enc=new TextEncoder();
    function stringOffset(text){
      text=String(text);if(stringOffsets.has(text))return stringOffsets.get(text);
      var bytes=Array.from(enc.encode(text)),at=strings.length;
      if(at+bytes.length+1>65535)throw new Error('Пул строк C превышает 64 КиБ');
      stringOffsets.set(text,at);strings.push.apply(strings,bytes);strings.push(0);return at;
    }
    function clipId(c){
      var v=[c.x,c.y,c.w,c.h],key=v.join(',');
      if(!clipIds.has(key)){clipIds.set(key,clips.length);clips.push(v)}return clipIds.get(key);
    }
    function primitiveId(q){
      var a=q.a.slice();if(q.t==='t')a[4]=stringOffset(a[4]);
      var compact={t:q.t,a:a,c:clipId(q.c),y:(q.b&&q.b.y)||0,h:(q.b&&q.b.h)||480};
      var key=keyOf(compact);
      if(!primitiveIds.has(key)){primitiveIds.set(key,primitives.length);primitives.push(compact)}
      return primitiveIds.get(key);
    }
    function blockId(ids){
      var key=ids.join(',');
      if(!blockIds.has(key)){blockIds.set(key,blocks.length);blocks.push(ids.slice())}return blockIds.get(key);
    }
    sceneEntries.forEach(function(entry){
      var groups=[],current=[],lastElement=null;
      entry.commands.forEach(function(q){
        var element=q.e||'';
        if(current.length&&element!==lastElement){groups.push(current);current=[]}
        current.push(primitiveId(q));lastElement=element;
      });
      if(current.length)groups.push(current);
      var first=sceneBlockIds.length;
      groups.forEach(function(group){sceneBlockIds.push(blockId(group))});
      scenes.push({id:ident(entry.name),name:entry.name,first:first,count:groups.length});
    });
    if(primitives.length>65535||blocks.length>65535||sceneBlockIds.length>65535)throw new Error('Индекс C превышает uint16_t');

    var primitiveWords=[],primitiveOffsets=[];
    primitives.forEach(function(p){
      primitiveOffsets.push(primitiveWords.length);
      primitiveWords.push(OP[p.t],p.c,p.y,p.h);
      if(p.t==='t')primitiveWords.push(p.a[0],p.a[1],p.a[2],p.a[3],p.a[4],p.a[5]?1:0,p.a[6]||0);
      else primitiveWords.push.apply(primitiveWords,p.a);
    });
    primitiveOffsets.push(primitiveWords.length);
    var blockCommands=[],blockOffsets=[];
    blocks.forEach(function(block){blockOffsets.push(blockCommands.length);blockCommands.push.apply(blockCommands,block)});
    blockOffsets.push(blockCommands.length);

    var header='#ifndef HMI_SCENE_GENERATED_H\n#define HMI_SCENE_GENERATED_H\n\n#include <stdint.h>\n\ntypedef enum {\n';
    scenes.forEach(function(s,i){header+='    HMI_SCENE_'+s.id+' = '+i+',\n'});
    header+='    HMI_SCENE_COUNT\n} HmiSceneId;\n\ntypedef struct { uint16_t first_block; uint16_t block_count; const char *name; } HmiGeneratedScene;\n\n';
    header+='extern const HmiGeneratedScene hmi_generated_scenes[HMI_SCENE_COUNT];\nextern const uint16_t hmi_generated_primitive_words[];\nextern const uint32_t hmi_generated_primitive_offsets[];\nextern const uint16_t hmi_generated_clip_rects[][4];\nextern const uint16_t hmi_generated_block_commands[];\nextern const uint16_t hmi_generated_block_offsets[];\nextern const uint16_t hmi_generated_scene_blocks[];\nextern const uint8_t hmi_generated_strings[];\nextern const uint32_t hmi_generated_data_bytes;\n\n#endif\n';

    var source='#include "hmi_scene_generated.h"\n\n/* AUTO-GENERATED by PCH-1000 HMI Editor. No raster frames. */\n';
    source+='const uint16_t hmi_generated_primitive_words[] = {\n'+lines(primitiveWords,'u',false)+'\n};\n';
    source+='const uint32_t hmi_generated_primitive_offsets[] = {\n'+lines(primitiveOffsets,'u',false)+'\n};\n';
    source+='const uint16_t hmi_generated_clip_rects[][4] = {\n';
    clips.forEach(function(c){source+=' {'+c.map(function(v){return (v&65535)+'u'}).join(',')+'},\n'});source+='};\n';
    source+='const uint16_t hmi_generated_block_commands[] = {\n'+lines(blockCommands,'u',false)+'\n};\n';
    source+='const uint16_t hmi_generated_block_offsets[] = {\n'+lines(blockOffsets,'u',false)+'\n};\n';
    source+='const uint16_t hmi_generated_scene_blocks[] = {\n'+lines(sceneBlockIds,'u',false)+'\n};\n';
    source+='const uint8_t hmi_generated_strings[] = {\n'+lines(strings,'',true)+'\n};\n';
    source+='const HmiGeneratedScene hmi_generated_scenes[HMI_SCENE_COUNT] = {\n';
    scenes.forEach(function(s){source+=' {'+s.first+'u,'+s.count+'u,"'+cString(s.name)+'"},\n'});source+='};\n';
    var total=primitiveWords.length*2+primitiveOffsets.length*4+clips.length*8+blockCommands.length*2+blockOffsets.length*2+sceneBlockIds.length*2+strings.length;
    source+='const uint32_t hmi_generated_data_bytes = '+total+'u;\n';
    return {header:header,source:source,stats:{scenes:scenes.length,primitives:primitives.length,blocks:blocks.length,bytes:total}};
  }
  var api={generate:generate};
  if(typeof module!=='undefined'&&module.exports)module.exports=api;
  root.CSceneGenerator=api;
})(typeof window!=='undefined'?window:this);
